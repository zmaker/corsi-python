'''
chiedo due numeri e calcolo somma e prodotto
'''

#chiedo il primo numero
ans = input("primo numero: ")
#trasformo la risposta in numero
a = int(ans)
#chiedo il secondo numero
ans = input("secondo numero: ")
#trasformo la risposta in numero
b = int(ans)

#calcolo somma
somma = a + b
#calcolo prodotto
prod = a * b
#stampo
print(f"somma di {a} + {b} = {somma}")
print(f"prod di {a} x {b} = {prod}")

print(f"incremento a {a+1} ")

