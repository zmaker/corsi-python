'''
EX: scrivere un programma python che chiede due numeri e stampa la somma

'''

# chiedo il primo numero
a = int( input("dammi il primo numero: ") )

# chiedo il secondo numero
b = int( input("dammi il secondo numero: ") )

# sommo i due numeri - il risultato è in una variabile "somma"
somma = a + b

# stampo il risultato
print(a, "+", b, "=", somma)