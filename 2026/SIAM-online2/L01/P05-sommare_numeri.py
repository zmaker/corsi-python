'''
Ex: scrivi un programma che chiede due numeri e stampa la somma
'''
print("Programma che somma due numeri:")

# chiedo un numero
n = int( input("dammi un numero: ") )

#chiedo un secondo numero
m = int( input("secondo numero: ") )

#sommo i numeri
s = n + m

#stampo il risultato
print(n, "+", m, "=", s)